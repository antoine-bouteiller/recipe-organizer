export const vars = createGlobalThemeContract(tokenValues, (_value, path) =>
  path
    .map((part) =>
      part
        .replaceAll(/(?<lower>[a-z0-9])(?<upper>[A-Z])/g, '$<lower>-$<upper>')
        .toLowerCase()
        .replaceAll('.', '-')
    )
    .join('-')
)

